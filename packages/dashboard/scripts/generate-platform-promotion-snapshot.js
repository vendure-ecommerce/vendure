#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/**
 * Writes the Platform catalog snapshot that ships with @vendure/dashboard
 * (vite/platform-promotion-snapshot.ts). The Dashboard build uses it when it
 * cannot fetch the catalog.
 *
 * Usage: node scripts/generate-platform-promotion-snapshot.js [source]
 *
 * `source` is a catalog URL or a path to a JSON file with the catalog response.
 * The default is the production catalog. The Core release runs this script.
 * It never exits with an error. If it cannot read a valid catalog, or if
 * VENDURE_DASHBOARD_SKIP_PLATFORM_CATALOG_FETCH is `true`, it keeps the
 * committed snapshot and prints a warning.
 */

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_FILE = path.join(__dirname, '../vite/platform-promotion-snapshot.ts');
const DEFAULT_SOURCE = 'https://api.vendure.io/v1/catalog';

const SKIP_ENV = 'VENDURE_DASHBOARD_SKIP_PLATFORM_CATALOG_FETCH';

async function readCatalog(source) {
    if (/^https?:\/\//.test(source)) {
        const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
        if (!response.ok) {
            throw new Error(`GET ${source} returned HTTP ${response.status}`);
        }
        return response.json();
    }
    return JSON.parse(fs.readFileSync(source, 'utf-8'));
}

async function generateSnapshot(source) {
    const catalog = await readCatalog(source);
    const dashboardPromotion = catalog?.dashboardPromotion;
    if (dashboardPromotion?.version !== 1) {
        throw new Error(`${source} has no dashboardPromotion with version 1`);
    }
    const output = `// This file is generated by scripts/generate-platform-promotion-snapshot.js. Do not edit it manually.
export const platformPromotionSnapshot = ${JSON.stringify(dashboardPromotion, null, 4)};
`;
    const prettier = await import('prettier');
    const prettierOptions = await prettier.resolveConfig(OUTPUT_FILE);
    fs.writeFileSync(
        OUTPUT_FILE,
        await prettier.format(output, { ...prettierOptions, filepath: OUTPUT_FILE }),
    );
    console.log(`Platform catalog snapshot updated from ${source}`);
}

// This script runs in the release `version` step. It must never fail a build or a publish,
// so on any problem it keeps the committed snapshot.
const source = process.argv[2] ?? DEFAULT_SOURCE;
if (process.env[SKIP_ENV] === 'true') {
    console.warn(`Platform catalog snapshot not changed: ${SKIP_ENV} is set.`);
} else {
    try {
        await generateSnapshot(source);
    } catch (e) {
        console.warn(`Platform catalog snapshot not changed: ${e instanceof Error ? e.message : String(e)}`);
    }
}
