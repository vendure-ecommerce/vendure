#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/**
 * Writes the Platform catalog snapshot that ships with @vendure/dashboard
 * (vite/platform-promotion-snapshot.ts). The Dashboard build uses it when it
 * cannot fetch the catalog.
 *
 * Usage: node scripts/generate-platform-promotion-snapshot.js [source]
 *
 * `source` is a catalog URL or a path to a JSON file with the catalog response.
 * The default is the production catalog. The Core release runs this script.
 */

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_FILE = path.join(__dirname, '../vite/platform-promotion-snapshot.ts');
const DEFAULT_SOURCE = 'https://api.vendure.io/v1/catalog';

async function readCatalog(source) {
    if (/^https?:\/\//.test(source)) {
        const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
        if (!response.ok) {
            throw new Error(`GET ${source} returned HTTP ${response.status}`);
        }
        return response.json();
    }
    return JSON.parse(fs.readFileSync(source, 'utf-8'));
}

const source = process.argv[2] ?? DEFAULT_SOURCE;
const catalog = await readCatalog(source);
const dashboardPromotion = catalog?.dashboardPromotion;
if (dashboardPromotion?.version !== 1) {
    console.error(`${source} has no dashboardPromotion with version 1. The snapshot is not changed.`);
    process.exit(1);
}

const output = `// This file is generated by scripts/generate-platform-promotion-snapshot.js. Do not edit it manually.
export const platformPromotionSnapshot = ${JSON.stringify(dashboardPromotion, null, 4)};
`;
fs.writeFileSync(OUTPUT_FILE, output);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)} from ${source}`);
